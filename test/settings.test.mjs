import fs from "fs";
import { log, state } from "herdr";
const home = process.env.MDHOME;
const { handleLink } = await import(`${home}/mods/md-view/link.js`);
const cfg = await import(`${home}/mods/md-view/config.js`);
let fails = 0;
const ok = (cond, what) => { console.log(`${cond ? "PASS" : "FAIL"}  ${what}`); if (!cond) fails++; };
const click = { link: { kind: "file", path: "/x/a.md" }, source: { tab: "T1", pane: "P1", terminal: "t1", machine: null, space: "S1" } };
const setCfg = (c) => fs.writeFileSync(`${home}/md-view.json`, JSON.stringify(c));
const go = async (c, panes = []) => { setCfg(c); state.panes = panes; log.length = 0; const r = await handleLink(click); return { r, calls: log.filter((l) => l[0] !== "setShared").map((l) => l[0]), log: [...log] }; };
const term = { pane: "P1", tab: "T1", terminal: "t1" }, panel = { pane: "P9", tab: "T1", mod: "md-view", terminal: null };

let x = await go({ placement: "right" }, [term]);
ok(x.r === "handled" && x.log.find((l) => l[0] === "pane.split")?.[1].direction === "right", "Beside: splits right");
ok(x.log.at(-1)[0] === "pane.focus" && x.log.at(-1)[1].pane === "P1", "Beside, keyboard off: focus goes back to the terminal");
x = await go({ placement: "down" }, [term]);
ok(x.log.find((l) => l[0] === "pane.split")?.[1].direction === "down", "Below: splits down");
x = await go({ placement: "right", focus_panel: true }, [term]);
ok(!x.calls.includes("pane.focus"), "Keyboard on: new panel keeps focus");
x = await go({ placement: "right" }, [term, panel]);
ok(!x.calls.includes("pane.split") && !x.calls.includes("pane.focus") && x.log.some((l) => l[0] === "setShared"), "Reuse on, panel open: no new pane, panel follows, terminal keeps keyboard");
x = await go({ placement: "right", focus_panel: true }, [term, panel]);
ok(x.log.some((l) => l[0] === "pane.focus" && l[1].pane === "P9"), "Reuse on, keyboard on: focuses the existing panel");
x = await go({ placement: "right", reuse_panel: false }, [term, panel]);
const sp = x.log.find((l) => l[0] === "pane.split");
ok(sp && sp[1].props.file === "/x/a.md" && !sp[1].props.tab, "Reuse off: new panel per file with its own file");
x = await go({ placement: "tab" }, [term]);
let tn = x.log.find((l) => l[0] === "tab.new");
ok(tn && tn[1].focus === true && tn[1].props.file === "/x/a.md" && tn[1].space === "S1", "New tab: tab.new with focus true in the clicked space");
x = await go({ placement: "background" }, [term]);
tn = x.log.find((l) => l[0] === "tab.new");
ok(tn && tn[1].focus === false, "Background tab: tab.new with focus false");
state.panes = [term]; log.length = 0;
ok((await handleLink({ link: { kind: "file", path: null }, source: click.source })) === "pass", "Remote/unresolved path passes to the next handler");

// settings file and mod.json
fs.rmSync(`${home}/md-view.json`, { force: true });
let l = await cfg.loadConfig();
ok(l.config.placement === "right" && l.config.send.mode === "paste" && !l.error, "No file: defaults");
setCfg({ send: { mode: "submit" } });
l = await cfg.loadConfig();
ok(l.config.send.mode === "submit" && l.config.send.format === "quote", "Partial file merges with defaults");
fs.writeFileSync(`${home}/md-view.json`, "{ broken");
l = await cfg.loadConfig();
ok(l.error && l.config.placement === "right", "Broken file: defaults and an error");
const modBefore = fs.readFileSync(`${home}/mods/md-view/mod.json`, "utf8");
ok(modBefore === cfg.modJson(["md", "markdown"], JSON.parse(modBefore)), "Shipped mod.json matches what Settings writes (no needless reload)");
fs.rmSync(`${home}/md-view.json`); log.length = 0;
await cfg.saveConfig({ ...cfg.DEFAULTS, file_types: ["md", "mdx", "txt"] });
const modAfter = JSON.parse(fs.readFileSync(`${home}/mods/md-view/mod.json`, "utf8"));
ok(modAfter.version === JSON.parse(modBefore).version && !!modAfter.version, "Changing file types keeps the mod's version");
ok(modAfter.link_handlers[0].pattern === "(?i)\\.(md|mdx|txt)$", "File types rewrite the link pattern");
ok(new RegExp(modAfter.link_handlers[0].pattern.replace("(?i)", ""), "i").test("/a/B.MDX"), "New pattern matches .MDX");
ok(state.shared["md-view.config-rev"] && JSON.parse(fs.readFileSync(`${home}/md-view.json`, "utf8")).file_types.length === 3, "Save writes the file and signals every panel");
log.length = 0; await cfg.saveConfig({ ...cfg.DEFAULTS, file_types: ["md", "mdx", "txt"] });
ok(!log.some((l) => l[0] === "write"), "Saving unchanged settings writes nothing");
await cfg.saveConfig({ ...cfg.DEFAULTS, file_types: [] });
ok(JSON.parse(fs.readFileSync(`${home}/mods/md-view/mod.json`, "utf8")).link_handlers[0].pattern === "(?i)\\.(md|markdown)$", "Empty file types fall back to md and markdown");
ok(await cfg.resolveFont({ font: "ui" }) === null && await cfg.resolveFont({ font: "mono" }, { font_family: "JetBrains Mono" }) === "JetBrains Mono" && await cfg.resolveFont({ font: "Inter" }) === "Inter", "Font: ui, mono and a named font");
console.log(fails ? `${fails} FAILED` : "all passed");
